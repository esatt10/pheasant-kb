class Resolver:
    name = "base"
    operations = ALL_OPERATIONS

    def __init__(self, harness: Any, registration: Registration):
        self.harness = harness
        self.registration = registration

    def resolve(self, selector: str | None) -> Revision:  # pragma: no cover - interface
        raise NotImplementedError

    def read_bytes(self, revision: Revision, path: str) -> bytes:  # pragma: no cover
        raise NotImplementedError


class FolderResolver(Resolver):
    name = "folder"

    @property
    def root(self) -> Path:
        return Path(self.registration.scope["root"])

    def _walk(self) -> list[dict]:
        root = self.root
        if not root.is_dir():
            raise NotFound(f"registered folder is unavailable: {self.registration.uri}")
        patterns = _ignore_patterns(root)
        entries: list[dict] = []
        for directory, dirs, files in os.walk(root, followlinks=False):
            dirs.sort()
            if ".git" in dirs:
                dirs.remove(".git")
            for name in sorted(files) + sorted(
                d for d in dirs if os.path.islink(os.path.join(directory, d))
            ):
                full = Path(directory) / name
                rel = full.relative_to(root).as_posix()
                entry = {"path": rel, "hidden": _hidden(rel), "ignored": ignored(rel, patterns)}
                try:
                    info = full.lstat()
                    if stat.S_ISLNK(info.st_mode):
                        target = full.resolve(strict=False)
                        if not target.exists():
                            entries.append(
                                {**entry, "kind": "unreadable", "reason": "dangling link"}
                            )
                            continue
                        if root.resolve() not in target.parents:
                            entries.append(
                                {**entry, "kind": "unreadable", "reason": "link escapes root"}
                            )
                            continue
                        if target.is_dir():
                            continue
                        info = target.stat()
                    elif not stat.S_ISREG(info.st_mode):
                        entries.append({**entry, "kind": "unreadable", "reason": "not a file"})
                        continue
                    data = full.read_bytes()
                except OSError as exc:
                    entries.append(
                        {**entry, "kind": "unreadable", "reason": exc.strerror or "error"}
                    )
                    continue
                entries.append(
                    {
                        **entry,
                        "kind": "file",
                        "size": len(data),
                        "digest": digest_bytes(data),
                        "binary": is_binary(data[:8192]),
                        "generated": is_generated(rel, data[:512]),
                    }
                )
        return entries

    def resolve(self, selector: str | None) -> Revision:
        entries = self._walk()
        snapshot = bool(self.registration.freshness.get("snapshot"))
        if snapshot:
            store: BlobStore = self.harness.blobs
            for item in entries:
                if item["kind"] == "file":
                    item["blob"] = store.put((self.root / item["path"]).read_bytes())
        manifest = canonical(entries)
        revision = digest_value(entries)
        mtime = max(
            (
                (self.root / e["path"]).stat().st_mtime
                for e in entries
                if e["kind"] == "file" and (self.root / e["path"]).exists()
            ),
            default=None,
        )
        return Revision(
            self.registration.id,
            revision,
            "snapshot" if snapshot else "manifest",
            self.harness.blobs.put_text(manifest, "application/json"),
            entries,
            mtime,
            now(),
            time_bound=not snapshot,
        )

    def read_bytes(self, revision: Revision, path: str) -> bytes:
        entry = revision.entry(path)
        if entry is None:
            raise NotFound(f"{path} is not in revision {revision.revision[:19]}")
        if entry["kind"] != "file":
            raise EntryUnreadable(f"{path} is unreadable: {entry.get('reason')}")
        if entry.get("blob"):
            return self.harness.blobs.get(entry["blob"])
        try:
            data = (self.root / path).read_bytes()
        except OSError as exc:
            raise EntryUnreadable(f"{path} is unreadable now: {exc.strerror}") from exc
        if digest_bytes(data) != entry["digest"]:
            raise RevisionMoved(
                f"{path} changed after revision {revision.revision[:19]} was resolved; "
                "re-resolve and re-read, or carry the earlier revision explicitly"
            )
        return data


class GitResolver(Resolver):
    name = "git"

    @property
    def root(self) -> Path:
        return Path(self.registration.scope["root"])

    def _git(self, *args: str, binary: bool = False) -> Any:
        result = subprocess.run(
            ["git", "-C", str(self.root), *args],
            capture_output=True,
            timeout=60,
            check=False,
        )
        if result.returncode != 0:
            raise NotFound(
                f"git {' '.join(args[:2])} failed: {result.stderr.decode(errors='replace')[:200]}"
            )
        return result.stdout if binary else result.stdout.decode("utf-8", errors="replace")

    def resolve(self, selector: str | None) -> Revision:
        ref = selector or self.registration.scope.get("ref") or "HEAD"
        commit = self._git("rev-parse", "--verify", f"{ref}^{{commit}}").strip()
        timestamp = float(self._git("show", "-s", "--format=%ct", commit).strip())
        listing = self._git("ls-tree", "-r", "-l", "-z", "--full-tree", commit)
        entries: list[dict] = []
        oids: list[tuple[int, str]] = []
        for record in filter(None, listing.split("\0")):
            meta, path = record.split("\t", 1)
            mode, kind, oid, size = meta.split()
            entry = {"path": path, "hidden": _hidden(path), "ignored": False, "oid": oid}
            if kind == "commit":
                entries.append({**entry, "kind": "unreadable", "reason": "submodule"})
            elif mode == "120000":
                entries.append({**entry, "kind": "unreadable", "reason": "symbolic link"})
            else:
                entries.append({**entry, "kind": "file", "size": int(size), "digest": "git:" + oid})
                oids.append((len(entries) - 1, oid))
        heads = self._heads([oid for _, oid in oids])
        for index, oid in oids:
            head = heads.get(oid, b"")
            entries[index]["binary"] = is_binary(head)
            entries[index]["generated"] = is_generated(entries[index]["path"], head)
        return Revision(
            self.registration.id,
            commit,
            "commit",
            self.harness.blobs.put_text(canonical(entries), "application/json"),
            entries,
            timestamp,
            now(),
            time_bound=False,
            extra={"ref": ref},
        )

    def _heads(self, oids: list[str]) -> dict[str, bytes]:
        if not oids:
            return {}
        result = subprocess.run(
            ["git", "-C", str(self.root), "cat-file", "--batch"],
            input=("\n".join(oids) + "\n").encode(),
            capture_output=True,
            timeout=120,
            check=False,
        )
        out, heads, offset = result.stdout, {}, 0
        for oid in oids:
            newline = out.index(b"\n", offset)
            header = out[offset:newline].split()
            size = int(header[2]) if len(header) == 3 else 0
            heads[oid] = out[newline + 1 : newline + 1 + min(size, 8192)]
            offset = newline + 1 + size + 1
        return heads

    def read_bytes(self, revision: Revision, path: str) -> bytes:
        entry = revision.entry(path)
        if entry is None:
            raise NotFound(f"{path} is not in commit {revision.revision[:12]}")
        if entry["kind"] != "file":
            raise EntryUnreadable(f"{path} is unreadable: {entry.get('reason')}")
        return self._git("cat-file", "blob", entry["oid"], binary=True)


class PheasantResolver(Resolver):
    """A source the region already indexes, read as the index holds it."""

    name = "pheasant"
    operations = ("resolve", "enumerate", "grep", "read", "compare")

    def _rows(self) -> list[Any]:
        scope = self.registration.scope
        state = self.harness.state
        rows = state.rows(
            "SELECT a.id, a.relative_path, a.sha256, a.size_bytes, a.mime_type, a.last_indexed_at "
            "FROM artifacts a JOIN sources s ON s.id=a.source_id WHERE s.name=? "
            "ORDER BY a.relative_path",
            (scope["source"],),
        )
        prefix = scope.get("prefix") or ""
        return [r for r in rows if str(r["relative_path"] or "").startswith(prefix)]

    def resolve(self, selector: str | None) -> Revision:
        entries = []
        for row in self._rows():
            rel = str(row["relative_path"] or "")
            entries.append(
                {
                    "path": rel,
                    "kind": "file",
                    "hidden": _hidden(rel),
                    "ignored": False,
                    "size": int(row["size_bytes"] or 0),
                    "digest": "sha256:" + str(row["sha256"] or ""),
                    "artifact_id": row["id"],
                    "binary": False,
                    "generated": is_generated(rel),
                }
            )
        if not entries:
            raise NotFound(f"pheasant source holds no documents: {self.registration.uri}")
        return Revision(
            self.registration.id,
            digest_value(entries),
            "index-manifest",
            self.harness.blobs.put_text(canonical(entries), "application/json"),
            entries,
            None,
            now(),
            time_bound=True,
        )

    def read_bytes(self, revision: Revision, path: str) -> bytes:
        from pheasant.services import source_browser

        entry = revision.entry(path)
        if entry is None:
            raise NotFound(f"{path} is not in the indexed revision")
        current = {r["relative_path"]: r for r in self._rows()}.get(path)
        if current is None or "sha256:" + str(current["sha256"]) != entry["digest"]:
            raise RevisionMoved(f"{path} was re-indexed after this revision was resolved")
        document = source_browser.read_document(
            self.harness.services,
            source_browser.ReadRequest(path=path, source_name=self.registration.scope["source"]),
        )
        return (document.get("content") or "").encode("utf-8")


class ConnectionResolver(Resolver):
    """A repository, folder or drive behind a connected account, read under its policy.

    The adapter pins what it lists (a GitHub commit; a Drive or OneDrive manifest of
    per-file checksums and versions) and every read is checked against the pin, so a
    file that moved under a reader is a ``RevisionMoved`` rather than different bytes
    under an old citation. The policy is asked before *every* read, cached or not.
    """

    name = "connection"
    operations = ("resolve", "enumerate", "grep", "read", "inspect", "materialize", "compare")

    def _adapter(self):
        from pheasant_harness import connections

        return connections.adapter_for(self.harness, self.registration.scope)

    def resolve(self, selector: str | None) -> Revision:
        pinned = self._adapter().resolve(self.registration.scope, selector)
        return Revision(
            self.registration.id,
            pinned.revision,
            pinned.kind,
            self.harness.blobs.put_text(canonical(pinned.entries), "application/json"),
            pinned.entries,
            pinned.revision_time,
            now(),
            time_bound=pinned.time_bound,
            extra=pinned.extra,
        )

    def read_bytes(self, revision: Revision, path: str) -> bytes:
        entry = revision.entry(path)
        if entry is None:
            raise NotFound(f"{path} is not in revision {revision.revision[:19]}")
        if entry["kind"] != "file":
            raise EntryUnreadable(f"{path} is unreadable: {entry.get('reason')}")
        scope = self.registration.scope
        adapter = self._adapter()
        self.harness.connections.check(
            scope["connection"], scope["provider"], "read", adapter.item_resource(scope, entry)
        )
        return adapter.read(scope, entry)


RESOLVERS = {
    cls.name: cls for cls in (FolderResolver, GitResolver, PheasantResolver, ConnectionResolver)
}


