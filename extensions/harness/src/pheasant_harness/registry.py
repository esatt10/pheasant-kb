_CREDENTIAL_QUERY = re.compile(r"(?i)(token|key|secret|password|sig|signature)=")


def refuse_credentials(uri: str) -> None:
    parts = urlsplit(uri)
    if parts.username or parts.password or _CREDENTIAL_QUERY.search(parts.query or ""):
        raise HarnessError("A registered URI never carries credentials. Use a connection instead.")


def parse_uri(uri: str, resolver: str | None, config: Any) -> tuple[str, dict]:
    parts = urlsplit(uri)
    refuse_credentials(uri)
    scheme = parts.scheme
    if scheme not in SCHEMES:
        raise HarnessError(
            f"Unsupported URI scheme {scheme!r}; use file://, git+file://, pheasant:// or "
            "connection://"
        )
    if scheme == "pheasant":
        source = parts.netloc
        if not source:
            raise HarnessError("pheasant:// URIs name a source: pheasant://<source>/<prefix>")
        return "pheasant", {"source": source, "prefix": unquote(parts.path.lstrip("/"))}
    from pheasant.security.path_policy import PathPolicyError, resolve_source_path

    try:
        root = resolve_source_path(unquote(parts.path), config)
    except PathPolicyError as exc:
        raise AccessDenied(str(exc)) from exc
    chosen = resolver or ("git" if (root / ".git").exists() else "folder")
    if chosen not in SCHEMES[scheme]:
        raise HarnessError(f"resolver {chosen!r} cannot read a {scheme}:// URI")
    if chosen == "git" and not (root / ".git").exists():
        raise HarnessError(f"{root} is not a git checkout")
    return chosen, {"root": str(root)}


class Registry:
    def __init__(self, harness: Any):
        self.harness = harness
        self.state = harness.state
        self.kb = harness.kb_id

    def register(
        self,
        uri: str,
        actor: str,
        *,
        resolver: str | None = None,
        label: str | None = None,
        scope: dict | None = None,
        freshness_policy: dict | None = None,
        operations: list[str] | None = None,
        classification: str = "internal",
    ) -> dict:
        refuse_credentials(uri)
        if urlsplit(uri).scheme == "connection":
            from pheasant_harness import connections

            if resolver not in (None, "connection"):
                raise HarnessError(f"resolver {resolver!r} cannot read a connection:// URI")
            chosen, parsed = "connection", connections.parse_connection_uri(self.harness, uri)
        else:
            chosen, parsed = parse_uri(uri, resolver, self.harness.config)
        supported = RESOLVERS[chosen].operations
        ops = tuple(operations or supported)
        unknown = set(ops) - set(supported)
        if unknown:
            raise Unsupported(f"{chosen} registrations cannot offer {sorted(unknown)}")
        if chosen == "connection":
            # A pointer the connection's policy does not cover is refused now, not at
            # the first read of a run that was promised it.
            why = connections.registration_reason(self.harness, parsed, ops)
            if why:
                self.harness.connections.record_denial(
                    parsed["connection"], parsed["provider"], "list", uri, why
                )
                raise connections.ConnectionDenied(why)
        merged = {**parsed, **{k: v for k, v in (scope or {}).items() if k not in parsed}}
        reg_id = (
            "reg_"
            + hashlib.sha256(f"{self.kb}\0{uri}\0{canonical(merged)}".encode()).hexdigest()[:16]
        )
        existing = self.state.rows(
            "SELECT * FROM harness_registrations WHERE kb_id=? AND id=?", (self.kb, reg_id)
        )
        if not existing:
            self.state.execute(
                "INSERT INTO harness_registrations(kb_id,id,uri,resolver,scope_json,freshness_json,"
                "operations_json,classification,label,registered_by,created_at) "
                "VALUES(?,?,?,?,?,?,?,?,?,?,?)",
                (
                    self.kb,
                    reg_id,
                    uri,
                    chosen,
                    canonical(merged),
                    canonical(freshness_policy or {"max_age_seconds": 0, "snapshot": False}),
                    canonical(list(ops)),
                    classification,
                    label or uri.rsplit("/", 1)[-1] or uri,
                    actor,
                    now(),
                ),
            )
        self.grant(reg_id, actor, actor)
        registration = self.get(reg_id)
        return {
            **registration.public(),
            "supported_operations": list(supported),
            "source_classification": classification,
            "created": not existing,
        }

    def get(self, reg_id: str) -> Registration:
        rows = self.state.rows(
            "SELECT * FROM harness_registrations WHERE kb_id=? AND id=?", (self.kb, reg_id)
        )
        if not rows:
            raise NotFound(f"Unknown registration: {reg_id}")
        return Registration.from_row(rows[0])

    def list(self, actor: str | None = None) -> list[dict]:
        rows = self.state.rows(
            "SELECT * FROM harness_registrations WHERE kb_id=? ORDER BY created_at", (self.kb,)
        )
        out = []
        for row in rows:
            reg = Registration.from_row(row)
            item = reg.public()
            item["authorized"] = actor is None or self.authorized(reg, actor)
            out.append(item)
        return out

    def grant(self, reg_id: str, principal: str, granted_by: str) -> None:
        self.state.execute(
            "INSERT INTO harness_grants(kb_id,registration_id,principal,granted_by,granted_at) "
            "VALUES(?,?,?,?,?) ON CONFLICT (kb_id,registration_id,principal) "
            "DO UPDATE SET revoked_at=NULL, granted_by=excluded.granted_by",
            (self.kb, reg_id, principal, granted_by, now()),
        )

    def revoke(self, reg_id: str, principal: str) -> dict:
        self.get(reg_id)
        self.state.execute(
            "UPDATE harness_grants SET revoked_at=? WHERE kb_id=? AND registration_id=? "
            "AND principal=?",
            (now(), self.kb, reg_id, principal),
        )
        return {"registration_id": reg_id, "principal": principal, "revoked": True}

    def authorized(self, reg: Registration, actor: str) -> bool:
        if reg.revoked_at is not None:
            return False
        rows = self.state.rows(
            "SELECT 1 FROM harness_grants WHERE kb_id=? AND registration_id=? AND principal=? "
            "AND revoked_at IS NULL",
            (self.kb, reg.id, actor),
        )
        return bool(rows)

    def require(self, reg_id: str, actor: str, operation: str) -> Registration:
        reg = self.get(reg_id)
        if not self.authorized(reg, actor):
            # Denied and missing are distinguished internally; the caller is
            # told only that it may not read this, which leaks no existence.
            raise AccessDenied(f"{actor} is not authorized to {operation} {reg_id}")
        if operation not in reg.operations:
            raise Unsupported(
                f"{reg.label} is registered for {list(reg.operations)}; {operation} is not offered"
            )
        return reg

    def resolver(self, reg: Registration) -> Resolver:
        return RESOLVERS[reg.resolver](self.harness, reg)

    def resolve(self, reg_id: str, actor: str, version_selector: str | None = None) -> Revision:
        reg = self.require(reg_id, actor, "resolve")
        revision = self.resolver(reg).resolve(version_selector)
        self.state.execute(
            "INSERT INTO harness_revisions(kb_id,registration_id,revision,kind,manifest_digest,"
            "entries,revision_time,retrieved_at,time_bound) VALUES(?,?,?,?,?,?,?,?,?) "
            "ON CONFLICT (kb_id,registration_id,revision) DO UPDATE SET "
            "retrieved_at=excluded.retrieved_at",
            (
                self.kb,
                reg.id,
                revision.revision,
                revision.kind,
                revision.manifest_digest,
                len(revision.entries),
                revision.revision_time,
                revision.retrieved_at,
                int(revision.time_bound),
            ),
        )
        return revision

    def revision(self, reg_id: str, revision: str, actor: str) -> Revision:
        """A revision resolved earlier, rebuilt from its manifest blob."""
        reg = self.require(reg_id, actor, "read")
        rows = self.state.rows(
            "SELECT * FROM harness_revisions WHERE kb_id=? AND registration_id=? AND revision=?",
            (self.kb, reg.id, revision),
        )
        if not rows:
            raise NotFound(f"revision {revision[:19]} of {reg_id} was never resolved here")
