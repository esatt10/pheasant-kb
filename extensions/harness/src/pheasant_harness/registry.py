"""The knowledge registry: a tenant-scoped URI, and a resolver that pins it.

``register`` records *where to look*: a pointer, who registered it, which
operations it supports and how fresh a read of it must be. It reads nothing.
``resolve`` turns the pointer into a revision -- a commit, a snapshot or a
manifest digest -- for an actor who is authorized *now*, and says whether that
revision can be re-read later (``time_bound``). Every later read names the
revision it reads, and a revision that moved underneath a reader is a
``RevisionMoved``, never a silent read of different bytes.

Four resolvers ship: ``git`` (a local checkout, pinned to a commit),
``folder`` (a directory, pinned to a manifest digest, optionally snapshotted
into the blob store so a later audit can re-read it), ``pheasant`` (a
source this region already indexes, pinned to its artifact digests) and
``connection`` (a repository, folder or drive reached through one of the
region's connected accounts, under that connection's harness policy -- see
``connections``).
"""

from __future__ import annotations

import fnmatch
import hashlib
import os
import re
import stat
import subprocess
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from typing import Any
from urllib.parse import unquote, urlsplit

from pheasant_harness.blobs import BlobStore
from pheasant_harness.common import (
    AccessDenied,
    HarnessError,
    NotFound,
    Unsupported,
    canonical,
    digest_bytes,
    digest_value,
    loads,
    new_id,
    now,
)

ALL_OPERATIONS = ("resolve", "enumerate", "grep", "read", "inspect", "materialize", "compare")
SCHEMES = {
    "file": ("folder", "git"),
    "git+file": ("git",),
    "pheasant": ("pheasant",),
    "connection": ("connection",),
}
GENERATED_NAMES = ("*.min.js", "*.min.css", "*_pb2.py", "*.pb.go", "*.lock", "package-lock.json")
GENERATED_DIRS = {"dist", "build", "node_modules", "__generated__", "vendor_generated"}
GENERATED_MARKERS = (b"@generated", b"DO NOT EDIT", b"Code generated by")


class RevisionMoved(HarnessError):
    status = 409
    code = "HARNESS_REVISION_MOVED"


class EntryUnreadable(HarnessError):
    status = 422
    code = "HARNESS_ENTRY_UNREADABLE"


@dataclass
class Registration:
    id: str
    uri: str
    resolver: str
    scope: dict
    freshness: dict
    operations: tuple[str, ...]
    classification: str
    label: str
    registered_by: str
    created_at: float
    revoked_at: float | None = None

    @classmethod
    def from_row(cls, row: Any) -> Registration:
        return cls(
            id=row["id"],
            uri=row["uri"],
            resolver=row["resolver"],
            scope=loads(row["scope_json"], {}),
            freshness=loads(row["freshness_json"], {}),
            operations=tuple(loads(row["operations_json"], [])),
            classification=row["classification"],
            label=row["label"],
            registered_by=row["registered_by"],
            created_at=row["created_at"],
            revoked_at=row["revoked_at"],
        )

    def public(self) -> dict:
        return {
            "id": self.id,
            "uri": self.uri,
            "resolver": self.resolver,
            "label": self.label,
            "scope": self.scope,
            "freshness_policy": self.freshness,
            "operations": list(self.operations),
            "classification": self.classification,
            "registered_by": self.registered_by,
            "created_at": self.created_at,
            "revoked": self.revoked_at is not None,
        }


@dataclass
class Revision:
    registration_id: str
    revision: str
    kind: str
    manifest_digest: str
    entries: list[dict]
    revision_time: float | None
    retrieved_at: float
    time_bound: bool
    extra: dict = field(default_factory=dict)

    def handle(self) -> dict:
        return {
            "registration_id": self.registration_id,
            "revision": self.revision,
            "kind": self.kind,
            "manifest_digest": self.manifest_digest,
            "entries": len(self.entries),
            "revision_time": self.revision_time,
            "retrieved_at": self.retrieved_at,
            "time_bound": self.time_bound,
            "integrity": "immutable" if not self.time_bound else "digest-checked",
        }

    def entry(self, path: str) -> dict | None:
        for item in self.entries:
            if item["path"] == path:
                return item
        return None


def _hidden(path: str) -> bool:
    return any(part.startswith(".") for part in PurePosixPath(path).parts)


def is_generated(path: str, head: bytes = b"") -> bool:
    name = PurePosixPath(path).name
    if any(fnmatch.fnmatch(name, pattern) for pattern in GENERATED_NAMES):
        return True
    if set(PurePosixPath(path).parts[:-1]) & GENERATED_DIRS:
        return True
    return any(marker in head[:512] for marker in GENERATED_MARKERS)


def is_binary(head: bytes) -> bool:
    return b"\x00" in head[:8192]


def _ignore_patterns(root: Path) -> list[str]:
    path = root / ".gitignore"
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return []
    return [line.strip() for line in lines if line.strip() and not line.startswith("#")]


def ignored(path: str, patterns: list[str]) -> bool:
    for pattern in patterns:
        bare = pattern.rstrip("/")
        if pattern.endswith("/"):
            if bare in PurePosixPath(path).parts[:-1]:
                return True
        elif fnmatch.fnmatch(path, bare) or fnmatch.fnmatch(PurePosixPath(path).name, bare):
            return True
    return False


